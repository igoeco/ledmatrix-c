/*
 * Author: Ramesh Yerraballi
 * Date: Fall 2026
 * Test program for the 16x16 LED Matrix (WS281B) from btf-lighting.com
 * The Datasheet (WS2812B-datasheet.pdf) for the sevice can be found in 
 * this project folder.
 * To connect to the MSPM0 simply connect as follows:
 * The device has three sets of wires. 
 *   The Female end, which is DIN, the Male end which is DOUT
 *   The middle where you can supply power(5V) and return(Gnd)
 * The color of the wires in the DIN and DOUT is as follows:
 *   Red: 5V, Green:DIN and White: Gnd
 * So connect as follows:
 * 5V on MSPM0   ---> Red input on WS281B
 * PB0 on MSPM0  ---> Green input on WS281B
 * Gnd on MSPm0  ---> White input on WS281B
 * Ideally we would put a level-shifter (74AHCT125) and a 330ohm 
 * resistor (See WS2812B-Breakout.png) so the 0-3.3v signal from the
 * microcontroller (PB0 output) is appropriately scaled to the 
 * expectations of the WS281B. The datasheet however says that
 * V_1H must be a min of 0.7V_DD and V_1L must be a mx of 03.V_DD
 * I am gussing this is the reason the setup seems to work without 
 * the level-shifter
*/

