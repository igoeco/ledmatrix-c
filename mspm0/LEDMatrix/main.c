static unsigned int rand_state = 1u;

static int rand(void)
{
    rand_state = rand_state * 1664525u + 1013904223u;
    return (int)((rand_state >> 16) & 0x7FFF);
}

int main(void)
{
    neopixel_strip_t strip;

    /* Initialise the NeoPixel strip: GPIO 3 = micro:bit edge pad P0 */
    neopixel_init(&strip, 0, 256);
    neopixel_set_color(&strip, 0, 0, 60, 0);
    neopixel_show(&strip);

    for (int i = 0; i < 256; i++){
       neopixel_set_color_and_show(&strip, i, rand()%16, rand()%16, rand()%16);
       Delay_ms(100);
    }
    /* Bind the LED matrix module to the strip */
    ledmatrix_init(&strip);

    /* Clear any state left by a previous session (e.g. MicroPython) */
    ClearPixels();
    ledmatrix_show();
    Delay_ms(500);

    while (1) {
      /* Draw the NoKing bitmap starting at (0,0), full 16×16 */
      //DrawBitmap(NoKing, 0, 0, 16, 16);
	  Say("===", "===",0, 0,0,0,0,0);
      ledmatrix_show();
      Delay_ms(1000);
      ClearPixels();
      ledmatrix_show();
      Delay_ms(1000);
    }
}
